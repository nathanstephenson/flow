import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

import { projectKey } from "../src/backend/worker/claude-state.ts";

/**
 * A Claude Code config root holding conversations, for Import tests (ADR 0039).
 *
 * The records are the shapes Claude Code writes, trimmed to the fields the importer reads plus a
 * little of the bookkeeping it must ignore. Written by hand rather than copied from a real session,
 * because a real one carries a system prompt, account ids and whatever its owner was working on.
 */
export const CONVERSATION = "0f971f93-147c-46c2-984f-c91301183ede";
export const OTHER_CONVERSATION = "562f1aa3-efa1-4773-b16c-5e145fb58484";

export type ClaudeCodeRecord = Record<string, unknown>;

/** Write `records` as conversation `id` under `config` for `scope`, and answer the file's path. */
export function writeConversation(config: string, scope: string, id: string, records: ClaudeCodeRecord[]): string {
  const dir = join(config, "projects", projectKey(scope));
  mkdirSync(dir, { recursive: true });
  const path = join(dir, `${id}.jsonl`);
  writeFileSync(path, records.map((record) => JSON.stringify(record)).join("\n") + "\n");
  return path;
}

let clock = Date.parse("2026-11-01T09:00:00.000Z");
const at = () => new Date((clock += 1_000)).toISOString();

export function prompt(uuid: string, content: unknown, extra: ClaudeCodeRecord = {}): ClaudeCodeRecord {
  return { type: "user", uuid, timestamp: at(), isSidechain: false, message: { role: "user", content }, ...extra };
}

export function reply(uuid: string, content: unknown[], extra: ClaudeCodeRecord = {}): ClaudeCodeRecord {
  return {
    type: "assistant",
    uuid,
    timestamp: at(),
    isSidechain: false,
    message: { id: `msg_${uuid}`, role: "assistant", model: "claude-opus-5-5", content },
    ...extra,
  };
}

/** One conversation with a prompt, a tool round trip, a reply, a slash command and a second turn. */
export function ordinaryConversation(): ClaudeCodeRecord[] {
  return [
    { type: "permission-mode", permissionMode: "auto", sessionId: CONVERSATION },
    { type: "file-history-snapshot", messageId: "x", snapshot: {} },
    prompt("u1", "<system-reminder>context for the model</system-reminder>Fix the failing test"),
    reply("a1", [{ type: "thinking", thinking: "", signature: "redacted" }]),
    reply("a2", [{ type: "tool_use", id: "toolu_1", name: "Bash", input: { command: "npm test" } }]),
    prompt("u2", [{ type: "tool_result", tool_use_id: "toolu_1", content: "1 failing", is_error: false }]),
    reply("a3", [{ type: "text", text: "Fixed: the assertion was off by one." }]),
    { type: "system", subtype: "turn_duration", uuid: "s1", durationMs: 10 },
    prompt("u3", "<local-command-caveat>Caveat: generated by a local command</local-command-caveat>", { isMeta: true }),
    prompt("u4", "<command-name>/review</command-name>\n<command-args>src/app.ts</command-args>"),
    reply("a4", [{ type: "text", text: "Looks good." }]),
    { type: "ai-title", aiTitle: "Fix failing test", sessionId: CONVERSATION },
    // A sidechain is a Subagent's own conversation; its words are not the parent's.
    reply("a5", [{ type: "text", text: "subagent chatter" }], { isSidechain: true }),
  ];
}
