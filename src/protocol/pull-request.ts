export type MergeMethod = "MERGE" | "SQUASH" | "REBASE";
export type PullRequestActionInput = { pr: PullRequestRef; headOid: string; baseBranch: string; method?: MergeMethod };
export type PullRequestRef = { repo: string; number: number; id: string };
export type PullRequestComment = {
  id: string;
  author: string;
  body: string;
  url: string;
  createdAt: string;
};
export type PullRequestReview = PullRequestComment & { state: string };
export type PullRequestThread = {
  id: string;
  path: string;
  line: number | null;
  isOutdated: boolean;
  isResolved: boolean;
  viewerCanReply: boolean;
  viewerCanResolve: boolean;
  viewerCanUnresolve: boolean;
  diffHunk: string;
  comments: PullRequestComment[];
};
export type PullRequestCheck = { name: string; status: string; url: string; runId?: number; jobId?: number };
export type PullRequestDetails = PullRequestRef & {
  url: string;
  title: string;
  body: string;
  state: "OPEN" | "MERGED" | "CLOSED";
  isDraft: boolean;
  reviewDecision: string | null;
  updatedAt: string;
  author: string;
  headRefName: string;
  headRepository?: string;
  headRefOid: string;
  baseRefName: string;
  mergeable: string;
  mergeStateStatus: string;
  viewerCanComment: boolean;
  mergeMethods: MergeMethod[];
  checks: PullRequestCheck[];
  comments: PullRequestComment[];
  reviews: PullRequestReview[];
  threads: PullRequestThread[];
};
export type PullRequestCommentInput = { pr: PullRequestRef; body: string; threadId?: string };
export type PullRequestThreadInput = { pr: PullRequestRef; threadId: string; resolved: boolean };
export type PullRequestEditInput = { pr: PullRequestRef; title: string; body: string };
export type PullRequestDraftInput = { pr: PullRequestRef; draft: boolean };
export type PullRequestRerunInput = { pr: PullRequestRef; runId: number };
export type PullRequestCheckLog = { text: string; truncated: boolean };
/** Where a Pull Request is read: the branch of an Agent Session's Scope, or a number in a Project. */
export type PullRequestTarget = { sessionId: string; project?: never } | { project: string; sessionId?: never };
export type PullRequestListItem = PullRequestRef & { title: string; author: string; state: "OPEN" | "CLOSED" | "MERGED"; isDraft: boolean; updatedAt: string; reviewRequested: boolean };
export type ReviewEvent = "APPROVE" | "REQUEST_CHANGES" | "COMMENT";
export type PullRequestReviewInput = { pr: PullRequestRef; event: ReviewEvent; body: string };
